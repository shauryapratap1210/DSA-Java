import java.util.*;

public class StringInput {
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);

        System.out.println("Enter String for nextLine()");
        String ch2=sc.nextLine();
        System.out.println("Output String is : "+ch2);
        System.out.println("Enter String for next()");
        String ch1=sc.next();
        System.out.println("Input string is : "+ch1);

    }
}
